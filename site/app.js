'use strict';

// ---------- audio (square-wave arcade beeps) ----------
const Sfx = (() => {
  let ctx = null;
  function ac() { if (!ctx) ctx = new (window.AudioContext || window.webkitAudioContext)(); return ctx; }
  function beep(freq, dur, when = 0, gain = 0.18) {
    const a = ac(), o = a.createOscillator(), g = a.createGain();
    o.type = 'square'; o.frequency.value = freq;
    g.gain.setValueAtTime(gain, a.currentTime + when);
    g.gain.exponentialRampToValueAtTime(0.001, a.currentTime + when + dur);
    o.connect(g).connect(a.destination);
    o.start(a.currentTime + when); o.stop(a.currentTime + when + dur + .02);
  }
  return {
    unlock() { ac().resume && ac().resume(); },
    countdown(n) { beep(n === 1 ? 880 : n === 2 ? 740 : 660, .12); },
    startBlast() { beep(330, .4); beep(494, .25, .12); },
    halfway() { beep(587, .1); beep(587, .1, .16); },
    done() { beep(523, .15); beep(659, .15, .16); beep(784, .35, .32); },
    finalWarn() { beep(988, .08); beep(988, .08, .12); beep(988, .08, .24); },
    tick() { beep(1174, .05, 0, .1); },
  };
})();

const Vib = {
  on: true,
  fire(pattern) { if (this.on && navigator.vibrate) navigator.vibrate(pattern); },
  countdown() { this.fire(80); },
  startBlast() { this.fire(200); },
  halfway() { this.fire([100, 50, 100]); },
  done() { this.fire([400, 100, 400]); },
  finalWarn() { this.fire([80, 40, 80, 40, 80]); },
};

// ---------- config UI ----------
const $ = (s) => document.querySelector(s);
const $$ = (s) => [...document.querySelectorAll(s)];

let mode = 'enmom';
let run = null;
let rafId = null;

function setMode(m) {
  mode = m;
  $$('.tab').forEach(x => x.classList.toggle('active', x.dataset.mode === m));
  renderFields();
}

// ---------- presets (generated by scripts/index-wods.py --emit-presets) ----------
function renderPresets() {
  const box = $('#presets');
  if (!box) return;
  box.innerHTML = '';
  if (typeof PRESETS !== 'undefined' && PRESETS.length) {
    const head = document.createElement('div');
    head.className = 'preset-head';
    head.textContent = `TODAY'S MISSIONS — ${PRESETS[0].date}`;
    box.appendChild(head);
    for (const p of PRESETS) box.appendChild(presetButton(p));
  }
  if (typeof HERO_WODS !== 'undefined' && HERO_WODS.length) {
    const det = document.createElement('details');
    det.className = 'hero-group';
    det.innerHTML = '<summary class="preset-head">HERO WODS ▾</summary>';
    for (const p of HERO_WODS) det.appendChild(presetButton(p));
    box.appendChild(det);
  }
}

function presetButton(p) {
  const b = document.createElement('button');
  b.className = 'preset';
  b.textContent = p.name;
  b.title = p.fields.scheme || p.fields.stations || '';
  b.addEventListener('click', () => applyPreset(p, b));
  return b;
}

function applyPreset(p, btn) {
  setMode(p.mode);
  for (const [id, val] of Object.entries(p.fields)) {
    const el = $('#f-' + id);
    if (el) el.value = val;
  }
  $$('.preset').forEach(x => x.classList.toggle('active', x === btn));
}

