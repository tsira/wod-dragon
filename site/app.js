function parseMSS(v) {
  if (!v || !v.trim()) return null;
  const m = v.trim().match(/^(\d+):(\d{1,2})$/);
  if (m) return (+m[1]) * 60 + (+m[2]);
  const n = Number(v.trim());
  return isNaN(n) ? null : n * 60; // bare number = minutes
}

function renderFields() {
  const box = $('#fields');
  box.innerHTML = '';
  for (const f of MODE_FIELDS[mode]) {
    const d = document.createElement('div');
    d.className = 'field';
    d.innerHTML = `<label for="f-${f.id}">${f.label}</label>` +
      (f.textarea
        ? `<textarea id="f-${f.id}" rows="3">${f.value}</textarea>`
        : `<input id="f-${f.id}" type="${f.type || 'text'}" value="${f.value}">`) +
      (f.hint ? `<div class="hint">${f.hint}</div>` : '');
    box.appendChild(d);
  }
}

function readConfig() {
  const v = (id) => ($('#f-' + id) ? $('#f-' + id).value : '');
  if (mode === 'enmom') {
    const stations = v('stations').split('\n').map(s => s.trim()).filter(Boolean);
    return { intervalSec: parseMSS(v('interval')) ?? 120, sets: Math.max(1, +v('sets') || 8),
             stations, scheme: null };
  }
  if (mode === 'fortime') return { capSec: parseMSS(v('cap')), scheme: v('scheme') };
  if (mode === 'amrap') return { durationSec: parseMSS(v('duration')) ?? 900, scheme: v('scheme') };
  return { sets: Math.max(1, +v('sets') || 3), restSec: parseMSS(v('rest')) ?? 120, scheme: v('scheme') };
}

// ---------- run lifecycle ----------
function engage() {
  const cfg = readConfig();
  const cues = {
    sound: $('#c-sound').checked,
    vibrate: $('#c-vibe').checked,
    endCountdown: $('#c-end').checked,
    startBlast: $('#c-start').checked,
    halfway: $('#c-half').checked,
  };
  Vib.on = cues.vibrate;
  if (cues.sound) Sfx.unlock();
  run = Engine.createRun(mode, cfg, cues, 10);
  run.schemeText = cfg.scheme || (cfg.stations && cfg.stations.length ? '' : null);
  Engine.start(run, Date.now());
  $('#config').classList.add('hidden');
  $$('.abort').forEach(b => b.classList.remove('hidden'));
  loop();
}

function endRun(status) {
  cancelAnimationFrame(rafId);
  const entry = {
    ts: new Date().toISOString(),
    summary: Engine.summary(run),
    durationSec: Math.round((Date.now() - run.startedMs) / 1000),
    rounds: run.rounds,
    status,
  };
  saveLog(entry);
  renderLog();
  if (status === 'complete') { if (run.cues.sound) Sfx.done(); Vib.done(); }
  setFace('done', 'COMPLETE', Engine.fmt(entry.durationSec), run.schemeText || '', roundText());
  $$('.abort').forEach(b => b.classList.add('hidden'));
  setTimeout(() => { $('#config').classList.remove('hidden'); }, 600);
  run = null;
}

function loop() {
  rafId = requestAnimationFrame(loop);
  if (!run) return;
  const frame = Engine.tick(run, Date.now());
  if (frame.status === 'finished') { endRun('complete'); return; }
  if (frame.status !== 'running') return;

  for (const cue of Engine.evalCues(run, frame)) {
    if (run.cues.sound) {
      if (cue.type === 'countdown') (cue.final ? Sfx.finalWarn : () => Sfx.countdown(cue.n))();
      if (cue.type === 'segment-start') Sfx.startBlast();
      if (cue.type === 'halfway') Sfx.halfway();
    }
    if (cue.type === 'countdown') Vib.countdown();
    if (cue.type === 'segment-start') Vib.startBlast();
    if (cue.type === 'halfway') Vib.halfway();
  }

  const seg = frame.seg;
  const final3 = frame.remaining != null && frame.remaining <= 3 && seg.kind !== 'rest';
  const state = final3 ? 'final' : seg.kind;
  const digits = seg.durationSec == null || seg.direction === 'up'
    ? Engine.fmt(frame.display) : Engine.fmtTenths(frame.display);
  setFace(state, seg.label, digits, stationText(seg), roundText(), frame.progress, frame.totalElapsed);

  // tap zones
  const open = seg.durationSec == null;
  $$('.tapzone').forEach(z => {
    z.classList.toggle('setdone', open);
    z.textContent = open ? '■ SET DONE ■' : (mode === 'amrap' || mode === 'fortime') ? `TAP = ROUND (${run.rounds})` : '';
    z.style.visibility = (open || mode === 'amrap' || mode === 'fortime') ? 'visible' : 'hidden';
  });
}

function stationText(seg) {
  if (seg.station) return seg.station;
  return run.schemeText || '';
}
function roundText() {
  if (!run) return '';
  const seg = Engine.cur(run);
  if (seg && seg.totalRounds) return `${seg.round}/${seg.totalRounds}`;
  if (mode === 'amrap' || mode === 'fortime') return `RNDS ${run.rounds}`;
  return '';
}

// ---------- render both device faces ----------
function setFace(state, label, digits, station, chip, progress, totalElapsed) {
  for (const dev of ['#phone', '#watch']) {
    const root = $(dev);
    root.className = root.className.replace(/state-\w+/g, '').trim() + ` state-${state}`;
    root.querySelector('.seg-label').textContent = label;
    root.querySelector('.digits').textContent = digits;
    root.querySelector('.station').textContent = station || '';
    root.querySelector('.round-chip').textContent = chip || '';
    root.querySelector('.round-chip').style.visibility = chip ? 'visible' : 'hidden';
    const te = root.querySelector('.total-elapsed');
    if (te) te.textContent = totalElapsed != null ? 'TOTAL ' + Engine.fmt(totalElapsed) : '';
  }
  const bar = $('#watch .bar');
  const C = 2 * Math.PI * 47;
  bar.style.strokeDasharray = C;
  bar.style.strokeDashoffset = progress == null ? 0 : C * (1 - progress);
}

function tapZone(e) {
  if (!run) return;
  const seg = Engine.cur(run);
  if (!seg) return;
  if (seg.durationSec == null) {
    const res = Engine.completeOpenSegment(run, Date.now());
    if (run.cues.sound) Sfx.startBlast();
    Vib.startBlast();
    if (res && res.done) endRun('complete');
  } else if (mode === 'amrap' || mode === 'fortime') {
    Engine.tapRound(run, Date.now());
    if (run.cues.sound) Sfx.tick();
    Vib.fire(40);
  }
  e.currentTarget.classList.remove('flash'); void e.currentTarget.offsetWidth;
  e.currentTarget.classList.add('flash');
}

// ---------- mission log ----------
const LOG_KEY = 'wodDragonRuns';
function saveLog(entry) {
  const l = JSON.parse(localStorage.getItem(LOG_KEY) || '[]');
  l.unshift(entry);
  localStorage.setItem(LOG_KEY, JSON.stringify(l.slice(0, 50)));
}
function renderLog() {
  const l = JSON.parse(localStorage.getItem(LOG_KEY) || '[]');
  $('#log ul').innerHTML = l.slice(0, 12).map(e => {
    const d = new Date(e.ts);
    const ds = `${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')} ` +
      `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
    const st = e.status === 'complete' ? 'COMPLETE' : `<span class="st-aborted">ABANDONED</span>`;
    const rounds = e.rounds ? ` — ${e.rounds} RNDS` : '';
    return `<li>[${ds}] ${e.summary} — ${st} — ${Engine.fmt(e.durationSec)}${rounds}</li>`;
  }).join('') || '<li>NO MISSIONS ON RECORD</li>';
}

// ---------- boot ----------
document.addEventListener('DOMContentLoaded', () => {
  renderFields();
  renderPresets();
  renderLog();
  $$('.tab').forEach(t => t.addEventListener('click', () => setMode(t.dataset.mode)));
  $('#engage').addEventListener('click', engage);
  $$('.tapzone').forEach(z => z.addEventListener('pointerdown', tapZone));
  $$('.abort').forEach(b => b.addEventListener('click', () => { if (run) { Engine.abort(run, Date.now()); endRun('aborted'); } }));
  setFace('work', 'STANDBY', '0:00', 'CONFIGURE MISSION AND ENGAGE', '');
});
